const seededAt = new Date().toISOString();

/** Day 1 笔记原句里的可复用词块，搭配判定（mockFeedback.isCollocated）直接用它。 */
function w(
  id: string,
  headword: string,
  pos: string,
  meaningZh: string,
  source: string,
  example: string,
  collocations: [string, string][] = [],
): Word {
  return {
    id,
    headword,
    pos,
    meaningZh,
    examples: [example],
    collocations: collocations.map(([phrase, gloss]) => ({ phrase, gloss })),
    mastery: 'passive',
    source,
    updatedAt: seededAt,
  };
}

